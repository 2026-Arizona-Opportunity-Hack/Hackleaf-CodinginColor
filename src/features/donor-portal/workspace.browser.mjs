import assert from "node:assert/strict";
import { chromium } from "@playwright/test";

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  const base = process.env.TEST_BASE_URL ?? "http://127.0.0.1:3102";
  await page.goto(`${base}/donor-portal/history?donorId=someone-else`);
  await page.getByRole("heading", { name: "Enter your donor demo first." }).waitFor();
  await page.getByRole("link", { name: "Register as donor", exact: true }).first().click();
  await page.getByLabel("First name", { exact: false }).fill("Avery");
  await page.getByLabel("Last name", { exact: false }).fill("Example");
  await page.getByLabel("Email *", { exact: true }).fill("avery-demo@example.org");
  await page.getByLabel("Phone (optional)").fill("555-0100");
  await page.getByLabel("Address line (optional)").fill("100 Fictional Way");
  await page.getByLabel("City (optional)").fill("Phoenix");
  await page.getByLabel("State / region (optional)").fill("AZ");
  await page.getByLabel("Postal code (optional)").fill("85001");
  await page.getByLabel("Show my simulated contributions").check();
  await page.screenshot({ path: "/tmp/hackleaf-donor-register.png", fullPage: true, caret: "initial" });
  await page.getByRole("button", { name: "Register demo donor", exact: true }).click();
  await page.getByRole("heading", { name: "Login as a donor", exact: true }).waitFor();
  assert.equal(await page.getByLabel("Demo email").inputValue(), "avery-demo@example.org");
  assert.equal(await page.locator('input[type="password"]').count(), 0);
  await page.getByRole("button", { name: "Enter donor demo", exact: true }).click();
  const navigation = page.getByRole("navigation", { name: "Main navigation" });
  await navigation.getByRole("link", { name: "Donation history", exact: true }).click();
  await page.getByRole("heading", { name: "Your history starts with your first contribution." }).waitFor();
  await navigation.getByRole("link", { name: "Donate", exact: true }).click();
  assert.equal(await page.getByLabel("Program designation").count(), 0);
  await page.getByLabel("Donation amount *", { exact: true }).fill("20");
  await page.getByLabel("Giving frequency").selectOption("monthly");
  await page.getByLabel("Donation note (optional)").fill("Fictional classroom support");
  await page.getByRole("button", { name: "Review donation", exact: true }).click();
  await page.getByRole("heading", { name: "Review your demo donation" }).waitFor();
  assert.match(await page.getByRole("region", { name: "Donation review" }).innerText(), /NGO priority order/);
  assert.match(await page.getByRole("region", { name: "Donation review" }).innerText(), /\$20/);
  await page.getByRole("button", { name: "Edit donation", exact: true }).click();
  assert.equal(await page.getByLabel("Giving frequency").inputValue(), "monthly");
  assert.equal(await page.getByLabel("Donation note (optional)").inputValue(), "Fictional classroom support");
  await page.getByRole("button", { name: "Review donation", exact: true }).click();
  await page.screenshot({ path: "/tmp/hackleaf-donor-review.png", fullPage: true, caret: "initial" });
  await page.getByRole("button", { name: "Confirm demo donation", exact: true }).click();
  await navigation.getByRole("link", { name: "Donation history", exact: true }).click();
  await page.getByRole("heading", { name: "My donation history", exact: true }).waitFor();
  const history = page.getByRole("listitem");
  await history.first().waitFor();
  assert.equal(await history.count(), 1);
  assert.match(await history.innerText(), /\$20[\s\S]*Anonymous[\s\S]*Fictional classroom support/);
  await page.getByRole("link", { name: "NGO demo", exact: true }).click();
  const card = page.getByRole("article", { name: "Laptops for hands-on learning", exact: true });
  assert.match(await card.innerText(), /\$1,270 raised of \$5,000/);
  await card.click();
  assert.match(await page.getByRole("dialog").innerText(), /Anonymous[\s\S]*\$20 allocated/);
  assert.doesNotMatch(await page.getByRole("dialog").innerText(), /Avery Example/);
  await page.keyboard.press("Escape");
  await navigation.getByRole("link", { name: "Donor portal", exact: true }).click();
  await navigation.getByRole("link", { name: "Donation history", exact: true }).click();
  await page.getByRole("heading", { name: "My donation history", exact: true }).waitFor();
  assert.equal(await history.count(), 1);
  await navigation.getByRole("link", { name: "My profile", exact: true }).click();
  assert.equal(await page.getByLabel("Phone (optional)").inputValue(), "555-0100");
  await page.getByLabel("Phone (optional)").fill("555-0101");
  await page.getByRole("button", { name: "Save profile changes", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Demo profile updated" }).waitFor();
  await navigation.getByRole("link", { name: "Donation history", exact: true }).click();
  await page.getByRole("heading", { name: "My donation history", exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: "/tmp/hackleaf-donor-history-mobile.png", fullPage: true, caret: "initial" });
  await page.getByRole("button", { name: "Log out of demo", exact: true }).click();
  await page.getByRole("heading", { name: "Login as a donor", exact: true }).waitFor();
  await page.getByLabel("Demo email").fill("donor1@example.org");
  await page.getByRole("button", { name: "Enter donor demo", exact: true }).click();
  await navigation.getByRole("link", { name: "Donation history", exact: true }).click();
  await page.getByRole("heading", { name: "My donation history", exact: true }).waitFor();
  assert.doesNotMatch(await page.locator("main").innerText(), /Fictional classroom support/);
  await page.getByRole("button", { name: "Log out of demo", exact: true }).click();
  await page.getByRole("heading", { name: "Login as a donor", exact: true }).waitFor();
  await page.reload();
  await page.getByLabel("Demo email").fill("avery-demo@example.org");
  await page.getByRole("button", { name: "Enter donor demo", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "No matching demo profile" }).waitFor();
  assert.deepEqual(errors, []);
  console.log("PASS registration/optional fields/demo login/gated history/review edit/anonymous contribution/shared NGO allocation/own history/logout/reload/mobile/no browser errors");
} finally { await browser.close(); }
