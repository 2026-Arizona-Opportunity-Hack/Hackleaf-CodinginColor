import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { chromium } from "@playwright/test";

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1680, height: 1050 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  const base = process.env.TEST_BASE_URL ?? "http://127.0.0.1:3102";
  await page.goto(`${base}/donation-requests`);
  await page.getByRole("heading", { name: "Donation requests", exact: true }).waitFor();
  assert.equal(await page.getByRole("article").count(), 4);
  assert.equal(await page.getByRole("progressbar").first().getAttribute("value"), "300000");
  await page.screenshot({ path: "/tmp/hackleaf-donation-requests-desktop.png", fullPage: true, caret: "initial" });
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download spreadsheet", exact: true }).click();
  const spreadsheet = await downloadEvent;
  assert.equal(spreadsheet.suggestedFilename(), "donation-requests-demo.csv");
  const csv = await readFile(await spreadsheet.path(), "utf8");
  assert.match(csv, /Donation title/);
  assert.match(csv, /AI Academy classroom essentials/);
  assert.match(csv, /"3000.00","3000.00","0.00"/);
  const create = page.getByRole("button", { name: "Make a donation request", exact: true });
  await create.click();
  await page.screenshot({ path: "/tmp/hackleaf-donation-request-form.png", caret: "initial" });
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Donation title").fill("Community learning kits");
  await dialog.getByLabel("Program").selectOption("summer-camp");
  await dialog.getByLabel("Amount required").fill("1250.50");
  await dialog.getByLabel("Donation type / frequency").selectOption("monthly");
  await dialog.getByLabel("What is the donation for?").fill("Funding for classroom materials and hands-on activity kits.");
  await dialog.getByRole("button", { name: "Create request", exact: true }).click();
  const card = page.getByRole("article", { name: "Community learning kits", exact: true });
  await card.waitFor();
  assert.match(await card.innerText(), /\$0 raised of \$1,250.50/);
  assert.match(await card.innerText(), /0% funded/);
  await card.getByRole("button", { name: "View Community learning kits", exact: true }).click();
  assert.match(await dialog.innerText(), /No donations received/);
  await page.keyboard.press("Escape");
  assert.equal(await dialog.count(), 0);
  assert.equal(await card.getByRole("button", { name: "View Community learning kits", exact: true }).evaluate((element) => element === document.activeElement), true);
  await card.getByRole("button", { name: "Edit Community learning kits", exact: true }).click();
  await dialog.getByLabel("Donation title").fill("Updated learning kits");
  await dialog.getByRole("button", { name: "Save changes", exact: true }).click();
  await page.getByRole("article", { name: "Updated learning kits", exact: true }).waitFor();
  await create.click();
  await dialog.getByLabel("Donation title").fill("Draft classroom request");
  await dialog.getByLabel("Amount required").fill("500");
  await dialog.getByLabel("What is the donation for?").fill("Materials for our next classroom session.");
  await dialog.getByRole("button", { name: "Save as draft", exact: true }).click();
  assert.equal(await page.getByRole("article").count(), 1);
  assert.match(await page.getByRole("article").innerText(), /Draft classroom request/);
  await page.getByRole("button", { name: "All requests", exact: false }).click();
  await page.getByLabel("Search donation requests").fill("no-matching-title");
  await page.getByRole("heading", { name: "No matching requests" }).waitFor();
  await page.getByRole("button", { name: "Clear search" }).click();
  const seeded = page.getByRole("article", { name: "Laptops for hands-on learning", exact: true });
  await seeded.getByRole("button", { name: "Edit Laptops for hands-on learning", exact: true }).click();
  await dialog.getByLabel("Amount required").fill("1250");
  await dialog.getByRole("button", { name: "Save changes", exact: true }).click();
  await page.getByRole("button", { name: "Completed", exact: false }).click();
  assert.match(await seeded.innerText(), /Funding goal reached/);
  assert.match(await seeded.innerText(), /100% funded/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "All requests", exact: false }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: "/tmp/hackleaf-donation-requests-mobile.png", fullPage: true, caret: "initial" });
  await create.click();
  await page.keyboard.press("Shift+Tab");
  assert.equal(await dialog.evaluate((element) => element.contains(document.activeElement)), true);
  assert.equal(await dialog.evaluate((element) => element.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: "/tmp/hackleaf-donation-form-mobile.png", caret: "initial" });
  await dialog.getByLabel("Donation title").fill("Mobile classroom request");
  await dialog.getByLabel("Amount required").fill("250");
  await dialog.getByLabel("What is the donation for?").fill("A classroom request created on a narrow screen.");
  await dialog.getByRole("button", { name: "Create request", exact: true }).click();
  await page.getByRole("article", { name: "Mobile classroom request", exact: true }).waitFor();
  await page.reload();
  assert.equal(await page.getByRole("article").count(), 4);
  assert.deepEqual(errors, []);
  console.log("PASS CSV download/content/create/zero funding/details/edit/drafts/search/completed progress/mobile/dialog focus and Escape/page reset/no browser errors");
} finally { await browser.close(); }
